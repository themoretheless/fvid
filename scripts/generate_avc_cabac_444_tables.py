"""Extract H.264 (06/2019) tables 9-25..9-33 from the pinned official PDF.
Authoring only: needs pdftotext and a local normative PDF; ordinary tests do not.
Official source: https://www.itu.int/rec/dologin_pub.asp?id=T-REC-H.264-201906-S%21%21PDF-E&lang=e&type=items
"""
import hashlib,re,subprocess,sys
from pathlib import Path
source=Path(sys.argv[1])
assert hashlib.sha256(source.read_bytes()).hexdigest()=='4d18ee180e1760565289e25d886e0228bb0aa8e3669074f7d340db80b1118687'
text=subprocess.check_output(['pdftotext','-layout',str(source),'-'],text=True).replace('−','-')
start=re.search(r'\f\s*Table 9-25 . Values of variables m and n for ctxIdx from 460 to 483',text).end()
end=text.index('9.3.1.2',start)
rows=[[None]*564 for _ in range(4)]
corrected_labels=0
for line in text[start:end].splitlines():
 values=line.split()
 if len(values) not in [9,18] or not all(re.fullmatch(r'-?\d+',v)for v in values):continue
 values=list(map(int,values))
 # Table 9-26 labels the right cell beside 497 as 641, outside its stated
 # 484..571 range. It is 541 (497+44); actual 641 occurs in Table 9-27.
 # This printed index typo persists in the 2024 revision. Never overwrite 641.
 if len(values)==18 and values[0]==497 and values[9]==641:
  values[9]=541;corrected_labels+=1
 for at in range(0,len(values),9):
  index=values[at];assert 460<=index<=1023,index
  for group in range(4):
   pair=tuple(values[at+1+group*2:at+3+group*2]);assert all(-128<=v<=127 for v in pair)
   assert rows[group][index-460]is None,(group,index)
   rows[group][index-460]=pair
assert corrected_labels==1
assert all(all(pair is not None for pair in group)for group in rows)
out=Path(__file__).resolve().parents[1]/'src/codec/avc_cabac_444_init.rs'
with out.open('w')as f:
 f.write('// Generated by scripts/generate_avc_cabac_444_tables.py from ITU-T H.264 (06/2019), tables 9-25..9-33.\n')
 f.write('// Contexts 460..1023; I/SI then cabac_init_idc 0, 1, 2. Base tables remain unchanged.\n')
 f.write('pub(super) const INIT_444: [[(i8, i8); 564]; 4] = [\n')
 for group in rows:
  f.write('    [\n')
  for m,n in group:f.write(f'        ({m}, {n}),\n')
  f.write('    ],\n')
 f.write('];\n')
print('extracted',sum(map(len,rows)),'normative context pairs')
